import { ACCESSORY_IDS, AURAS, BG_IDS, BROW_IDS, BeatSchema, EFFECT_TYPES, EGO_TYPES, EMOTIONS, EYE_IDS, FACE_IDS, HAIR_IDS, MARK_IDS, NOSE_IDS, POSITIONS, REL_FIELDS, REL_STATUSES, REP_AXES, RES_KEYS, SKILLS, TONES } from './schemas'
import { collectFlagRefs } from './refs'
import type { ContentDB } from './types'

const beatTypes = BeatSchema.options.map((o) => o.shape.t.def.values[0] as string)

const list = (ids: readonly string[]) => ids.map((i) => `\`${i}\``).join(' ')
const table = (head: string[], rows: string[][]) =>
  [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n')

/** Markdown listing every id in the project. Generated by `npm run ids`; a test fails if docs/IDS.md is stale. */
export function buildIdList(c: ContentDB): string {
  const chars = Object.values(c.characters)
  const flags = [...new Set(collectFlagRefs(c).map((r) => r.name))].sort()
  return `# Every id in the project

> Generated by \`npm run ids\` from the game content. Do not edit by hand (a test fails if this file is stale).

## Characters: art file \`public/assets/portraits/<id>.png\`
${table(['id', 'name', 'kind'], chars.map((x) => [`\`${x.id}\``, x.name, x.kind + (x.placeholder ? ' (placeholder)' : '')]))}

Extra: \`player\` is your own character (\`portraits/player.png\` overrides the whole creator mix).
Expression art: \`<id>_<emotion>.png\` with emotion one of ${list(EMOTIONS)}.

## Player creator parts: \`public/assets/player/<slot>/<id>.png\` (1000 × 1300, see \`public/assets/player/README.md\`)
${table(['slot', 'built-in ids (drawn fallback; use the same id to replace it with an image)'], [
    ['face', list(FACE_IDS)], ['hair', list(HAIR_IDS)], ['eyes', list(EYE_IDS)], ['brow', list(BROW_IDS)], ['nose', list(NOSE_IDS)], ['mark', list(MARK_IDS)], ['accessory', list(ACCESSORY_IDS)],
  ])}

New ids are allowed: any \`<id>.png\` you add becomes an extra option. Once a slot has any image, only images are offered for that slot.

## Backgrounds: \`public/assets/backgrounds/<id>.jpg\`
${list(BG_IDS)}

## Voice
- Random clips: \`public/assets/voice/<characterId>/*.mp3\` (optional \`<emotion>/\` subfolders). Character ids: see Characters above, plus \`player\`.
- Exact lines: \`public/assets/voice/<scriptId>_<beatIndex>.mp3\` (see \`docs/voice-script.csv\`, generated by \`npm run voice:export\`).

## Origins
${table(['id', 'name', 'locked'], Object.values(c.origins).map((o) => [`\`${o.id}\``, o.name, o.locked ? 'yes (unlock via playthrough/Sandbox)' : 'no']))}

## Weapons
${table(['id', 'name', 'levels', 'starting weapon'], Object.values(c.weapons).map((w) => [`\`${w.id}\``, w.name, w.levels.map((l) => l.name).join(' → '), w.seedable ? 'can be rolled' : 'no']))}

## Traits
${table(['id', 'name'], Object.values(c.traits).map((t) => [`\`${t.id}\``, t.name]))}

## Arcs
${table(['id', 'name'], Object.values(c.arcs).map((a) => [`\`${a.id}\``, a.name]))}

## Scenes (scripts)
${table(['id', 'title', 'gallery'], Object.values(c.scripts).map((s) => [`\`${s.id}\``, s.title, s.gallery ? 'yes' : '']))}

## Events
${table(['id', 'title', 'cast', 'only when scheduled'], Object.values(c.events).map((e) => [`\`${e.id}\``, e.title, e.cast.map((x) => `\`${x}\``).join(' '), e.scheduledOnly ? 'yes' : '']))}

## Story flags (authored)
${list(flags)}

Dynamic flags use \`NAME:<characterId>\`, e.g. \`DEVOUR_TARGET:barou\`.

## Enums
- **Dialogue tones:** ${list(TONES)}
- **Relationship statuses:** ${list(REL_STATUSES)}
- **Relationship fields:** ${list(REL_FIELDS)}
- **Emotions:** ${list(EMOTIONS)}
- **Auras:** ${list(AURAS)}
- **Skills:** ${list(SKILLS)}
- **Reputation axes:** ${list(REP_AXES)}
- **Resources:** ${list(RES_KEYS)}
- **Positions:** ${list(POSITIONS)}
- **Ego types:** ${list(EGO_TYPES)}

## Script beat types
${list(beatTypes)}

## Effect types
${list(EFFECT_TYPES)}
`
}
